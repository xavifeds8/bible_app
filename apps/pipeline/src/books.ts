/** Normalize a book name from a source into the canonical form. */
export function normalizeBookName(name: string): string {
  return name
    .replace(/\bI\b/g, "1")
    .replace(/\bII\b/g, "2")
    .replace(/\bIII\b/g, "3")
    .replace(/^Revelation of John$/, "Revelation")
    .trim();
}

export function bookSlug(name: string): string {
  return name.toLowerCase().replace(/\s+/g, "-");
}
